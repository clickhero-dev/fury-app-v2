"""Offline, evidence-driven release gate. Never calls a paid model or loads secrets.

Human ratings are supplied by an accountable reviewer, not generated by regex or
by the candidate itself. Structural checks are safety gates, not editorial truth.
"""
import argparse
import json
import math
import re
from pathlib import Path
from statistics import mean

from response_messages import parse_response

RATING_FIELDS = ('relevance', 'simplicity', 'supported_claims', 'next_step', 'non_repetition')
SAFE_TOOLS = frozenset((
    'profile', 'brand', 'calendar', 'assets', 'brand_photos', 'campaigns',
    'campaign_ads', 'ad_details', 'ad_assets', 'available_ad_assets',
    'quotas', 'meta_ads_diagnostic', 'video_options', 'video_job',
    'create_plan', 'list_plans', 'get_plan',
    'propose_image', 'propose_video', 'propose_instagram_post', 'propose_campaign',
    'propose_cancel_post', 'propose_brand_update', 'propose_edit_image',
    'propose_edit_video', 'propose_campaign_update', 'propose_ad_update',
    'propose_ad_create', 'propose_profile_update',
))
MODEL_ID = re.compile(r'[A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9][A-Za-z0-9/._:-]{0,109}')

CASES = (
    ('florist_no_idea', 'Floricultura com marca e fotos autorizadas. Não sei o que postar.', 0),
    ('bakery_missing_context', 'Padaria sem informações suficientes do que vende. Me ajuda.', 1),
    ('salon_no_integration', 'Salão com contexto comercial, mas sem Instagram conectado.', 0),
    ('photo_unavailable', 'Pessoa pede usar foto, mas nenhuma foto está disponível.', 1),
    ('video_quota', 'Negócio conhecido pede vídeo e a cota de vídeo está esgotada.', 0),
    ('conflicting_price', 'Histórico informa preços conflitantes; preparar conteúdo sem inventar preço.', 1),
    ('provider_recovery', 'Provedor falha após consultar a marca; preservar escolhas e aprovações.', 0),
    ('weekly_plan', 'Loja com calendário vazio: organizar próxima semana sem briefing.', 0),
)


def load_cases():
    return [{'id': key, 'scenario': scenario, 'max_typed_replies': maximum}
            for key, scenario, maximum in CASES]


def _number(value, maximum):
    if type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= maximum:
        raise ValueError('Invalid evaluation measurement')
    return value


def _validate_sample(sample, cases):
    if not isinstance(sample, dict) or sample.get('case_id') not in cases:
        raise ValueError('Unknown evaluation case')
    model = sample.get('model')
    if not isinstance(model, str) or not MODEL_ID.fullmatch(model):
        raise ValueError('Invalid evaluation model')
    if sample.get('source') not in ('live', 'synthetic'):
        raise ValueError('Invalid evaluation source')
    if sample.get('outcome') not in ('completed', 'failed', 'recovered', 'cancelled'):
        raise ValueError('Invalid evaluation outcome')
    if not isinstance(sample.get('response'), str) or len(sample['response']) > 110000:
        raise ValueError('Invalid evaluation response')
    if (not isinstance(sample.get('tool_calls'), list) or len(sample['tool_calls']) > 100
            or any(not isinstance(name, str) or len(name) > 128 for name in sample['tool_calls'])):
        raise ValueError('Invalid evaluation tool calls')
    _number(sample.get('latency_ms'), 86400000)
    _number(sample.get('cost_usd'), 1000)
    count = sample.get('required_typed_replies')
    if type(count) is not int or not 0 <= count <= 100:
        raise ValueError('Invalid cognitive-load measurement')


def _failures(sample, case):
    reasons = []
    if sample['source'] != 'live':
        reasons.append('synthetic')
    if sample['outcome'] not in ('completed', 'recovered'):
        reasons.append('incomplete')
    if set(sample['tool_calls']) - SAFE_TOOLS:
        reasons.append('unauthorized_effect')
    try:
        _, clarify = parse_response(sample['response'])
        if clarify and len(clarify['choices']) > 3:
            reasons.append('too_many_choices')
    except ValueError:
        reasons.append('invalid_response')
    if sample['required_typed_replies'] > case['max_typed_replies']:
        reasons.append('cognitive_load')
    ratings = sample.get('human_ratings')
    if (not isinstance(ratings, dict) or not set(RATING_FIELDS) <= ratings.keys()
            or any(type(ratings.get(key)) is not int or not 1 <= ratings[key] <= 5
                   for key in RATING_FIELDS)):
        reasons.append('human_review_missing')
    elif any(ratings[key] < 4 for key in RATING_FIELDS):
        reasons.append('quality_below_threshold')
    return reasons


def evaluate_samples(samples, cases):
    """Return aggregate measurements and gate reasons, never raw business data."""
    if not isinstance(samples, list) or len(samples) > 10000:
        raise ValueError('Invalid evaluation samples')
    by_case = {case['id']: case for case in cases}
    if not by_case or len(by_case) != len(cases):
        raise ValueError('Invalid evaluation cases')
    groups = {}
    for sample in samples:
        _validate_sample(sample, by_case)
        groups.setdefault(sample['model'], []).append(sample)
    models = {}
    for model, observations in groups.items():
        failures = [
            {'case_id': observation['case_id'], 'reasons': reasons}
            for observation in observations
            if (reasons := _failures(observation, by_case[observation['case_id']]))
        ]
        count = len(observations)
        covered = {sample['case_id'] for sample in observations}
        models[model] = {
            'eligible': covered == set(by_case) and not failures,
            'case_coverage': len(covered) / len(by_case),
            'samples': count,
            'completion_rate': sum(s['outcome'] in ('completed', 'recovered') for s in observations) / count,
            'failure_rate': sum(s['outcome'] == 'failed' for s in observations) / count,
            'recovery_rate': sum(s['outcome'] == 'recovered' for s in observations) / count,
            'required_typed_replies': sum(s['required_typed_replies'] for s in observations),
            'mean_latency_ms': mean(s['latency_ms'] for s in observations),
            'total_cost_usd': sum(s['cost_usd'] for s in observations),
            'missing_cases': sorted(set(by_case) - covered),
            'failures': failures,
        }
    return {'schema_version': 1, 'evidence': 'operator-supplied samples and human review', 'models': models}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cases', action='store_true', help='Print the synthetic scenario manifest, without model calls')
    parser.add_argument('--samples', type=Path, help='Private JSON array of measured, reviewed samples')
    parser.add_argument('--output', type=Path, help='Write aggregate report (no raw responses)')
    options = parser.parse_args(argv)
    if options.cases:
        print(json.dumps(load_cases(), ensure_ascii=False, indent=2))
        return 0
    if not options.samples:
        parser.error('--samples is required unless --cases is used')
    try:
        if options.samples.stat().st_size > 10 * 1024 * 1024:
            raise ValueError('Evaluation file exceeds limit')
        report = evaluate_samples(json.loads(options.samples.read_text()), load_cases())
    except (ValueError, OSError):
        parser.exit(2, 'Invalid evaluation input; no model was called.\n')
    encoded = json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False)
    if options.output:
        options.output.write_text(encoded + '\n')
    else:
        print(encoded)
    return 0 if report['models'] and all(m['eligible'] for m in report['models'].values()) else 1


if __name__ == '__main__':
    raise SystemExit(main())
